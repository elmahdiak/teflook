export interface LocalizedProductData {
  title: string;
  description: string;
  categoryName: string;
  categoryBadge: string;
  features: string[];
  material?: string;
  origin?: string;
  vendor: string;
}

export function getLocalizedProduct(
  product: ShopifyProduct,
  locale: Locale
): LocalizedProductData {
  if (locale === "ar") {
    const tr = PRODUCT_TRANSLATIONS_AR[product.id] || PRODUCT_TRANSLATIONS_AR[product.handle];
    return {
      title: tr?.title || product.title_ar || product.title,
      description: tr?.description || product.description_ar || product.description,
      categoryName: tr?.categoryName || product.categoryNameAr || "تيفلوك",
      categoryBadge: tr?.categoryBadge || getLocalizedCategoryBadge(product, "ar"),
      features: tr?.features || product.features_ar || product.features || [],
      material: tr?.material || product.material_ar || product.material,
      origin: tr?.origin || product.origin_ar || product.origin,
      vendor: product.vendor_ar || "تيفلوك",
    };
  }

  // French (default)
  return {
    title: product.title_fr || product.title,
    description: product.description_fr || product.description,
    categoryName: product.productType || "TefLook",
    categoryBadge: getLocalizedCategoryBadge(product, "fr"),
    features: product.features || [],
    material: product.material,
    origin: product.origin,
    vendor: product.vendor || "TefLook",
  };
}

export function getLocalizedCategoryBadge(
  product: ShopifyProduct,
  locale: Locale
): string {
  const cat = getChildStoreCategory(product);

  if (locale === "ar") {
    const tr = PRODUCT_TRANSLATIONS_AR[product.id] || PRODUCT_TRANSLATIONS_AR[product.handle];
    if (tr?.categoryBadge) return tr.categoryBadge;

    const mappingAr: Record<string, string> = {
      discipline: "تيفلوك - انضباط",
      emotionalIntelligence: "تيفلوك - تعاطف",
      independence: "تيفلوك - استقلالية",
      confidence: "تيفلوك - تواصل",
      creativity: "تيفلوك - إبداع",
      criticalThinking: "تيفلوك - منطق",
    };
    if (cat && mappingAr[cat]) return mappingAr[cat];
    return "تيفلوك";
  }

  // French
  const mappingFr: Record<string, string> = {
    discipline: "TEFLOOK MAÎTRISE",
    emotionalIntelligence: "TEFLOOK EMPATHIE",
    independence: "TEFLOOK AUTONOMIE",
    confidence: "TEFLOOK SOCIAL",
    creativity: "TEFLOOK CRÉATIVITÉ",
    criticalThinking: "TEFLOOK LOGIQUE",
  };
  if (cat && mappingFr[cat]) return mappingFr[cat];
  if (product.vendor) {
    const v = product.vendor.toUpperCase();
    return v.startsWith("TEFLOOK") ? v : `TEFLOOK ${v}`;
  }
  return "TEFLOOK SOCIAL";
}
